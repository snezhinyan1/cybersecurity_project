#  Помехоустойчивое кодирование (Код Хэмминга 7,4).
#  Реализация алгоритма помехоустойчивого кодирования. Структура кода Хэмминга
#  позволяет выявлять и автоматически корректировать одиночные ошибки в переданных
#  блоках данных путем вычисления синдрома на основе битов четности.

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def hamming_74_encode(data_bits):
    # Извлечение информационных битов из входного массива.
    d1, d2, d3, d4 = data_bits

    # Вычисление контрольных битов четности с использованием операции сложения по модулю 2.
    p1 = d1 ^ d2 ^ d4
    p2 = d1 ^ d3 ^ d4
    p3 = d2 ^ d3 ^ d4

    # Формирование кодового слова длиной 7 бит с размещением контрольных битов на позициях степеней двойки.
    return [p1, p2, d1, p3, d2, d3, d4]


def hamming_74_decode_and_fix(encoded_bits):
    # Извлечение всех переданных битов из кодового слова.
    p1, p2, d1, p3, d2, d3, d4 = encoded_bits

    # Вычисление компонентов синдрома ошибки для локализации искаженного бита.
    s1 = p1 ^ d1 ^ d2 ^ d4
    s2 = p2 ^ d1 ^ d3 ^ d4
    s3 = p3 ^ d2 ^ d3 ^ d4

    # Декодирование двоичного синдрома в целочисленный индекс позиции ошибки.
    error_pos = s1 * 1 + s2 * 2 + s3 * 4

    if error_pos > 0:
        print(f"Зарегистрировано искажение в бите {error_pos}. Производится коррекция.")
        # Инверсия искаженного бита для восстановления исходного состояния.
        encoded_bits[error_pos - 1] ^= 1

    # Возврат восстановленной последовательности информационных битов.
    return [encoded_bits[2], encoded_bits[4], encoded_bits[5], encoded_bits[6]]


original = [1, 0, 1, 1]
encoded = hamming_74_encode(original)

# Имитация аппаратного сбоя накопителя в процессе передачи данных.
encoded[6] = 0
print("Восстановленная последовательность:", hamming_74_decode_and_fix(encoded))
