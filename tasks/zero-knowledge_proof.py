# Учебная модель протокола Шнорра. Проверяющий сопоставляет ответ с обязательством, вызовом и
# открытым ключом. Малые параметры позволяют восстановить секрет перебором.

import secrets
import sys


def zkp_schnorr():
    # Модуль и основание являются открытыми параметрами группы малой мощности.
    p = 23
    g = 2
    period = 11  # Порядок основания равен 11, поскольку 2¹¹ ≡ 1 (mod 23).

    # Фиксированное закрытое число используется доказывающей стороной для вычисления открытого
    # ключа.
    secret = 6
    public_key = pow(g, secret, p)

    # На первом шаге выбирается одноразовый показатель, который остаётся у доказывающей стороны.
    nonce = secrets.randbelow(period - 1) + 1
    # Проверяющему передаётся обязательство в виде степени основания с одноразовым показателем.
    commitment = pow(g, nonce, p)

    # На втором шаге проверяющий выбирает случайный ненулевой вызов.
    challenge = secrets.randbelow(period - 1) + 1

    # На третьем шаге ответ связывает одноразовый показатель, вызов и секрет по модулю порядка
    # группы.
    response = (nonce + challenge * secret) % period

    # На четвёртом шаге вычисляется степень основания с показателем, равным полученному ответу.
    left_side = pow(g, response, p)
    # Правая часть строится из обязательства и открытого ключа, возведённого в степень вызова.
    right_side = (commitment * pow(public_key, challenge, p)) % p

    print(f"Сравнение значений при верификации: {left_side} == {right_side}")

    # Равенство подтверждает, что ответ удовлетворяет уравнению проверки.
    return left_side == right_side


# Демонстрационный блок выполняется только при запуске модуля как программы.
if __name__ == "__main__":
    # Если поток поддерживает настройку, для вывода кириллицы используется UTF-8.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    print("Статус завершения протокола верификации:", zkp_schnorr())
