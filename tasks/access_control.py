# Ролевое управление доступом. Разрешения на операции с документом определяются по таблице ролей.

"""Реализуйте проверку прав доступа к документу.

Вход — роль пользователя и действие. Результат — разрешено ли действие.
Читатель может читать, редактор — читать и изменять, администратор — ещё и удалять.
Неизвестные роли и действия должны получать отказ.
"""

import sys


# Каждой роли сопоставляется множество разрешённых операций.
PERMISSIONS = {
    "viewer": {"read"},
    "editor": {"read", "edit"},
    "admin": {"read", "edit", "delete"},
}


def can_access(role, action):
    # Роль считается уже установленной. Для неизвестной роли используется пустое множество
    # разрешений.
    allowed_actions = PERMISSIONS.get(role, set())
    # Операция разрешается только при наличии в наборе разрешений данной роли.
    return action in allowed_actions


# Демонстрационный блок выполняется только при запуске модуля как программы.
if __name__ == "__main__":
    # Если поток поддерживает настройку, для вывода кириллицы используется UTF-8.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    # Сопоставляются три заданные роли и роль, отсутствующая в таблице.
    for role in ("viewer", "editor", "admin", "unknown"):
        print(f"Роль {role}")
        # Для каждой роли проверяются все три операции с документом.
        for action in ("read", "edit", "delete"):
            print(f"  Действие {action} разрешено: {can_access(role, action)}")
