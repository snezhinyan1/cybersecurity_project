# Сложение и удвоение точек эллиптической кривой над полем вычетов по небольшому простому модулю.

import math
import sys


def ecc_point_addition(P, Q, a, p):
    """Складывает точки одной кривой при небольшом простом модуле p > 3."""
    # Формулы применяются над простым полем характеристики больше трёх.
    if type(p) is not int or p <= 3:
        raise ValueError("Модуль должен быть простым числом больше трёх.")
    # Достаточно проверить делители до целой части квадратного корня из модуля.
    if any(p % divisor == 0 for divisor in range(2, math.isqrt(p) + 1)):
        raise ValueError("Модуль должен быть простым числом.")
    if type(a) is not int:
        raise ValueError("Коэффициент кривой должен быть целым числом.")

    # Конечная точка должна быть представлена парой целочисленных координат.
    for point in (P, Q):
        if point is not None and (
            not isinstance(point, (list, tuple))
            or len(point) != 2
            or any(type(value) is not int for value in point)
        ):
            raise ValueError("Точка должна содержать две целочисленные координаты.")
    # Координаты приводятся к каноническим остаткам, чтобы сравнивать представителей одной точки.
    if P is not None:
        P = (P[0] % p, P[1] % p)
    if Q is not None:
        Q = (Q[0] % p, Q[1] % p)

    # Точка на бесконечности, обозначенная None, является нейтральным элементом сложения.
    if P is None:
        return Q
    if Q is None:
        return P

    x1, y1 = P
    x2, y2 = Q

    # Свободный член кривой вычисляется из уравнения каждой конечной точки.
    b1 = (y1**2 - x1**3 - a * x1) % p
    b2 = (y2**2 - x2**3 - a * x2) % p
    # Одинаковый свободный член необходим для принадлежности точек одной кривой.
    if b1 != b2:
        raise ValueError("Точки должны принадлежать одной кривой.")
    # Нулевой дискриминант соответствует вырожденной кривой.
    if (4 * a**3 + 27 * b1**2) % p == 0:
        raise ValueError("Параметры задают вырожденную кривую.")

    # Вертикальная прямая соответствует сумме, равной точке на бесконечности. Сюда входит удвоение
    # при y = 0.
    if x1 == x2 and (y1 + y2) % p == 0:
        return None

    if P == Q:
        # Для удвоения используются числитель и знаменатель наклона касательной.
        numerator = (3 * x1**2 + a) % p
        denominator = (2 * y1) % p
    else:
        # Для различных точек наклон секущей определяется разностями координат.
        numerator = (y2 - y1) % p
        denominator = (x2 - x1) % p

    # По малой теореме Ферма степень p − 2 даёт обратный элемент ненулевого знаменателя.
    inv_denominator = pow(denominator, p - 2, p)
    # Умножение на обратный элемент выполняет деление в поле вычетов.
    m = (numerator * inv_denominator) % p

    # Формулы определяют третью точку пересечения с последующим отражением по координате y.
    x3 = (m**2 - x1 - x2) % p
    y3 = (m * (x1 - x3) - y1) % p

    return (x3, y3)


# Демонстрационный блок выполняется только при запуске модуля как программы.
if __name__ == "__main__":
    # Если поток поддерживает настройку, для вывода кириллицы используется UTF-8.
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    # Пример на кривой y² = x³ + 2x + 2 (по модулю 17).
    p_mod = 17
    a_curve = 2
    point_G = (5, 1)

    print(
        "Результат операции удвоения точки:",
        ecc_point_addition(point_G, point_G, a_curve, p_mod),
    )
