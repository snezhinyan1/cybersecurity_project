#  Эллиптическая криптография (ECC).
#  Реализация операции сложения точек на эллиптической кривой в конечном поле.
#  Данная математическая структура является базисом современных протоколов асимметричной
#  криптографии, позволяя использовать ключи меньшего размера при высокой криптостойкости.

import sys

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")


def ecc_point_addition(P, Q, a, p):
    # Обработка нейтрального элемента (точки на бесконечности).
    if P == (0, 0):
        return Q
    if Q == (0, 0):
        return P

    x1, y1 = P
    x2, y2 = Q

    if P != Q:
        # Вычисление углового коэффициента секущей прямой для двух различных точек.
        numerator = (y2 - y1) % p
        denominator = (x2 - x1) % p
    else:
        # Вычисление углового коэффициента касательной прямой для операции удвоения точки.
        numerator = (3 * x1**2 + a) % p
        denominator = (2 * y1) % p

    # Нахождение мультипликативно обратного элемента в конечном поле с использованием Малой теоремы Ферма.
    inv_denominator = pow(denominator, p - 2, p)
    m = (numerator * inv_denominator) % p

    # Вычисление координат результирующей точки пересечения с последующим симметричным отражением.
    x3 = (m**2 - x1 - x2) % p
    y3 = (m * (x1 - x3) - y1) % p

    return (x3, y3)


# Инициализация параметров показательной эллиптической кривой вида y^2 = x^3 + 2x mod 17.
p_mod = 17
a_curve = 2
point_G = (5, 1)

print(
    "Результат операции удвоения точки:",
    ecc_point_addition(point_G, point_G, a_curve, p_mod),
)
